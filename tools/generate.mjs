#!/usr/bin/env node
// Generates the C++ dictionary tables from data/*.json.
//
//   node tools/generate.mjs           generate core/*_gen.* (asserts the contract first)
//
// Outputs:
//   core/dictionary_gen.cpp             the Entry + per-language index tables
//   core/normalization_fixtures_gen.h   the shared fold fixtures, for the C++ test
//
// The normalize() here MUST produce the same output as core/normalize.cpp for every
// case in data/normalization-fixtures.json (ADR-0002); this script asserts that before
// emitting anything, so a divergence fails the build rather than corrupting the index.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (rel) => JSON.parse(readFileSync(join(ROOT, rel), "utf8"));

// --- the normalization contract (mirror of core/normalize.cpp) ---------------------

const MULTI = {
  "ß": "ss", "ẞ": "ss", "æ": "ae", "Æ": "ae", "œ": "oe", "Œ": "oe",
  "ø": "o", "Ø": "o", "ð": "d", "Ð": "d",
};

function normalize(input) {
  let expanded = "";
  for (const ch of input) expanded += MULTI[ch] ?? ch;
  return expanded
    .normalize("NFD")               // split base letter + combining diacritic
    .replace(/[̀-ͯ]/g, "") // drop the diacritics
    .toLowerCase()
    .replace(/[^a-z0-9 '\-]/g, "")   // keep only the key alphabet
    .replace(/\s+/g, " ")            // collapse runs of spaces
    .trim();
}

function assertContract() {
  const { cases } = readJson("data/normalization-fixtures.json");
  const failures = cases.filter(([input, want]) => normalize(input) !== want);
  if (failures.length) {
    for (const [input, want] of failures) {
      console.error(`  normalize(${JSON.stringify(input)}) = ${JSON.stringify(normalize(input))}, want ${JSON.stringify(want)}`);
    }
    throw new Error(`normalization contract broken for ${failures.length} case(s)`);
  }
  return cases;
}

// --- C++ emission helpers -----------------------------------------------------------

const cstr = (s) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

function buildIndex(entries, pick) {
  const rows = [];
  entries.forEach((entry, id) => {
    for (const term of pick(entry)) {
      const norm = normalize(term);
      if (norm) rows.push({ norm, id });
    }
  });
  rows.sort((a, b) => (a.norm < b.norm ? -1 : a.norm > b.norm ? 1 : a.id - b.id));
  // Drop exact (norm,id) duplicates (e.g. two glosses that fold to the same key).
  return rows.filter((r, i) => i === 0 || r.norm !== rows[i - 1].norm || r.id !== rows[i - 1].id);
}

// --- main ---------------------------------------------------------------------------

const langMeta = readJson("data/languages.json");
const order = langMeta.query_order;           // ["tp","en","es","fr","de","pt"]
const glossLangs = order.filter((l) => l !== "tp");

const fixtures = assertContract();
const { entries } = readJson("data/dictionary.json");

// Validate the source corpus — fail loud on anything the C++ side cannot trust.
entries.forEach((e, i) => {
  if (!e.tp || typeof e.tp !== "string") throw new Error(`entry ${i}: missing 'tp' headword`);
  for (const l of glossLangs) {
    if (e[l] !== undefined && !Array.isArray(e[l])) throw new Error(`entry ${i} (${e.tp}): '${l}' must be an array`);
  }
});
if (entries.length > 0xffff) throw new Error("entry count exceeds uint16 id space");

// Emit the dictionary tables.
let out = "";
out += "// GENERATED by tools/generate.mjs from data/*.json — DO NOT EDIT.\n";
out += '#include "dictionary.hpp"\n\nnamespace tp {\n\n';

entries.forEach((e, id) => {
  for (const lang of order) {
    const glosses = lang === "tp" ? [e.tp] : (e[lang] ?? []);
    const items = glosses.map(cstr).concat("nullptr").join(", ");
    out += `static const char* const g${id}_${lang}[] = { ${items} };\n`;
  }
});

out += "\nconst Entry ENTRIES[] = {\n";
entries.forEach((e, id) => {
  const sitelen = e.sitelen ?? e.tp;
  const lists = order.map((l) => `g${id}_${l}`).join(", ");
  out += `  { ${cstr(e.tp)}, ${cstr(sitelen)}, { ${lists} } },\n`;
});
out += "};\n";
out += `const uint16_t ENTRY_COUNT = ${entries.length};\n\n`;

const indexNames = [];
for (const lang of order) {
  const rows = lang === "tp"
    ? buildIndex(entries, (e) => [e.tp])
    : buildIndex(entries, (e) => e[lang] ?? []);
  const name = `idx_${lang}`;
  indexNames.push({ name, size: rows.length });
  out += `static const IndexRow ${name}[] = {\n`;
  for (const r of rows) out += `  { ${cstr(r.norm)}, ${r.id} },\n`;
  out += "};\n";
}

out += `\nconst IndexRow* const INDEX_BY_LANG[LangCount] = { ${indexNames.map((x) => x.name).join(", ")} };\n`;
out += `const uint16_t INDEX_SIZE_BY_LANG[LangCount] = { ${indexNames.map((x) => x.size).join(", ")} };\n`;

// Human-readable language labels for the detail view, in cycle order. Sourced from
// languages.json so the language set stays a data change, never an app-code edit (ADR-0001).
const labels = order.map((l) => {
  const meta = langMeta.languages[l];
  if (!meta || !meta.native) throw new Error(`languages.json: '${l}' missing a 'native' label`);
  return cstr(meta.native);
});
out += `const char* const LANG_LABEL[LangCount] = { ${labels.join(", ")} };\n`;
out += "\n}  // namespace tp\n";

writeFileSync(join(ROOT, "core/dictionary_gen.cpp"), out);

// Emit the shared normalization fixtures for the C++ test.
let fx = "";
fx += "// GENERATED by tools/generate.mjs from data/normalization-fixtures.json — DO NOT EDIT.\n";
fx += "#pragma once\n\nstruct NormCase { const char* in; const char* out; };\n";
fx += "static const NormCase NORM_CASES[] = {\n";
for (const [input, want] of fixtures) fx += `  { ${cstr(input)}, ${cstr(want)} },\n`;
fx += "};\n";
fx += `static const int NORM_CASE_COUNT = ${fixtures.length};\n`;
writeFileSync(join(ROOT, "core/normalization_fixtures_gen.h"), fx);

const totalRows = indexNames.reduce((s, x) => s + x.size, 0);
console.log(`generated ${entries.length} entries, ${totalRows} index rows across ${order.length} languages`);
